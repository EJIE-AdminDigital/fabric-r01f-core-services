package r01f.core.messaging.rabbitmq.producer.bootstrap;

import com.google.inject.Binder;
import com.google.inject.Module;


import r01f.messaging.rabbitmq.producer.RabbitMQProducerServiceConfig;

public abstract class RabbitMQProducerGuiceModuleBase<K,V>
		implements Module {
/////////////////////////////////////////////////////////////////////////////////////////
//MEMBERS
/////////////////////////////////////////////////////////////////////////////////////////
	final Class<K> _keyClassType;
	final Class<V> _valueClassType;
	final RabbitMQProducerServiceConfig _cfg;
/////////////////////////////////////////////////////////////////////////////////////////
//	CONSTRUCTOR
/////////////////////////////////////////////////////////////////////////////////////////
	public RabbitMQProducerGuiceModuleBase( final Class<K> keyClassType, final Class<V> valueClassType	,
			                                final RabbitMQProducerServiceConfig cfg ) {
		_cfg = cfg;
		_valueClassType = valueClassType;
		_keyClassType = keyClassType;
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	CONFIGURE
/////////////////////////////////////////////////////////////////////////////////////////
	@Override
	public void configure(final Binder binder) {
		_bindServiceConfig(binder);
		_bindProducerSerializers(binder);
		_bindProducerService(binder);
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	BINDINGS TO IMPLEMENT
/////////////////////////////////////////////////////////////////////////////////////////
	protected abstract void _bindProducerService(final Binder binder);
	protected abstract void _bindProducerSerializers(final Binder binder);
/////////////////////////////////////////////////////////////////////////////////////////
//	BINDINGS TO IMPLEMENT
/////////////////////////////////////////////////////////////////////////////////////////
	protected  void _bindServiceConfig(final Binder binder) {
		binder.bind(RabbitMQProducerServiceConfig.class)
			   .toInstance(_cfg);
	}
}
