package r01f.core.messaging.kafka.consumer.bootstrap;

import com.google.inject.Binder;
import com.google.inject.Module;

import r01f.messaging.kafka.consumer.KafkaConsumerServiceConfig;

public abstract class KafkaConsumerGuiceModuleBase<K,V>
		implements Module {
/////////////////////////////////////////////////////////////////////////////////////////
//MEMBERS
/////////////////////////////////////////////////////////////////////////////////////////
	final Class<K> _keyClassType;
	final Class<V> _valueClassType;
	final KafkaConsumerServiceConfig _cfg;
/////////////////////////////////////////////////////////////////////////////////////////
//	CONSTRUCTOR
/////////////////////////////////////////////////////////////////////////////////////////
	public KafkaConsumerGuiceModuleBase( final Class<K> keyClassType, final Class<V> valueClassType	,
			                             final KafkaConsumerServiceConfig cfg ) {
		_cfg = cfg;
		_valueClassType = valueClassType;
		_keyClassType = keyClassType;
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	CONFIGURE
/////////////////////////////////////////////////////////////////////////////////////////
	@Override
	public void configure(final Binder binder) {
		_bindServiceConfig(binder);
		_bindConsumerDeserializers(binder);
	    _bindConsumerService(binder);
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	BINDINGS TO IMPLEMENT
/////////////////////////////////////////////////////////////////////////////////////////
	protected abstract void _bindConsumerService(final Binder binder);
	protected abstract void _bindConsumerDeserializers(final Binder binder);
/////////////////////////////////////////////////////////////////////////////////////////
//	BINDINGS TO IMPLEMENT
/////////////////////////////////////////////////////////////////////////////////////////
	protected  void _bindServiceConfig(final Binder binder) {
		binder.bind(KafkaConsumerServiceConfig.class)
			   .toInstance(_cfg);
	}
}
