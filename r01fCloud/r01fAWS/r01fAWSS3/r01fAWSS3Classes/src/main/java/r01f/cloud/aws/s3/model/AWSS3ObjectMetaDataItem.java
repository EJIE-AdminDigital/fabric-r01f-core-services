package r01f.cloud.aws.s3.model;

public record AWSS3ObjectMetaDataItem(AWSS3ObjectMetadataItemId id,
									  String value) {
/////////////////////////////////////////////////////////////////////////////////////////
//	
/////////////////////////////////////////////////////////////////////////////////////////	
	public static AWSS3ObjectMetaDataItem from(final AWSS3ObjectMetadataItemId id,
											   final String value) {
		return new AWSS3ObjectMetaDataItem(id,
										   value);
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	
/////////////////////////////////////////////////////////////////////////////////////////	
	public AWSS3ObjectMetadataItemId getId() {
		return this.id;
	}
	public String getValue() {
		return this.value;
	}
}
